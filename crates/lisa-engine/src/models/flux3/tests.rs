#[test]
fn flow_map_schedule_has_reference_endpoints_and_order() {
    for steps in [1, 4, 16, 50] {
        let t = schedule(steps);
        assert_eq!(t.len(), steps as usize + 1);
        assert_eq!(t[0], 1.0);
        assert_eq!(*t.last().unwrap(), 0.0);
        assert!(t.windows(2).all(|w| w[0] > w[1]));
    }
    assert_eq!(schedule(2)[1], 16.0 / 17.0);
}

pub(crate) fn compare(
    name: &str,
    actual: &Array,
    expected: &Array,
    max_relative_rmse: f64,
) -> anyhow::Result<()> {
    assert_eq!(actual.shape(), expected.shape(), "{name}");
    let actual = actual.as_dtype(Dtype::Float32)?.contiguous()?;
    let expected = expected.as_dtype(Dtype::Float32)?.contiguous()?;
    actual.eval()?;
    expected.eval()?;
    let a = actual.as_slice::<f32>();
    let b = expected.as_slice::<f32>();
    let mut error = 0.0;
    let mut norm = 0.0;
    let mut dot = 0.0;
    let mut anorm = 0.0;
    let mut max = 0f32;
    for (&a, &b) in a.iter().zip(b) {
        assert!(a.is_finite() && b.is_finite(), "{name}: non-finite output");
        error += (a as f64 - b as f64).powi(2);
        norm += (b as f64).powi(2);
        dot += a as f64 * b as f64;
        anorm += (a as f64).powi(2);
        max = max.max((a - b).abs());
    }
    let relative = (error / norm.max(1e-30)).sqrt();
    eprintln!(
        "{name}: relative_rmse={relative:.8} cosine={:.8} max_abs={max}",
        dot / (anorm * norm).sqrt()
    );
    assert!(
        relative <= max_relative_rmse,
        "{name}: relative RMSE {relative} > {max_relative_rmse}"
    );
    Ok(())
}

/// Explicit external-data check, never a silent pass when the checkpoint is absent.
/// Fixtures are generated by the pinned BFL code and Transformers Qwen3-VL path.
#[test]
#[ignore = "requires LISA_FLUX3_MODEL and LISA_FLUX3_FIXTURES; one GPU job at a time"]
fn flux3_reference_stages() -> anyhow::Result<()> {
    let dir = PathBuf::from(std::env::var("LISA_FLUX3_MODEL")?);
    let fixtures = PathBuf::from(std::env::var("LISA_FLUX3_FIXTURES")?);
    let expected = Weights::load_file(&fixtures.join("stages.safetensors"), |_| true)?;
    let prompt = std::fs::read_to_string(fixtures.join("prompt.txt"))?;
    {
        let encoder = text::Encoder::load(&dir)?;
        compare(
            "encoder",
            &encoder.encode(&prompt)?,
            &expected.get("text")?,
            0.03,
        )?;
    }
    lisa_mlx::memory::clear_cache();
    {
        let model = dit::Dit::load(&dir)?;
        let velocity = model.forward(
            &expected.get("latent")?,
            &expected.get("text")?.as_dtype(Dtype::Bfloat16)?,
            0.5,
            0.25,
            4,
            6,
        )?;
        compare("denoiser", &velocity, &expected.get("velocity")?, 0.03)?;
    }
    lisa_mlx::memory::clear_cache();
    {
        let weights = decoder_weights(&dir)?;
        let latent = expected
            .get("latent")?
            .reshape(&[1, 4, 6, 128])?
            .transpose_axes(&[0, 3, 1, 2])?;
        let pixels = vae::decode_weights(&weights, &latent, Dtype::Float32)?;
        compare("decoder", &pixels, &expected.get("pixels")?, 0.001)?;
    }
    Ok(())
}
